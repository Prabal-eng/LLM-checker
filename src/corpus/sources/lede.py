"""LEDE, English part: news articles generated from a real article's title and summary by 2025-26 frontier
models (NeurIPS 2026 submission). https://huggingface.co/datasets/NeurIPS-2026-LEDE/LEDE-dataset (CC-BY-NC-4.0).

Held out whole (split.HOLDOUT_SOURCES) as v4's frontier news test; AI only, so it measures detection.
Only the frontier models are read (Claude 4.5-4.6, GPT-5.x, Gemini 3.1), and only the three strategies that
write an article from the facts (sc, ib, ng): "we" (writing enhancement) polishes the human article
itself, an AI-edited label the pre-registration does not use. Capped at PER_MODEL articles per model.
"""

from pathlib import Path
from typing import Iterable

import pandas as pd

from ..schema import Label, LicenceClass, Role, Sample
from ._common import SourceSpec, compact, make_sample, take_per_stratum

_BASE = "https://huggingface.co/datasets/NeurIPS-2026-LEDE/LEDE-dataset/resolve/main/"
FRONTIER = ("Claude_Opus_4.6", "Claude_Sonnet_4.5", "Claude_Sonnet_4.6", "GPT_5", "Gemini_3.1")
_MODELS = ("Claude_Opus_4.6", "Claude_Sonnet_4.5", "Claude_Sonnet_4.6", "GPT_5", "GPT_5_nano", "GPT_5.4",
           "GPT_5.4_nano", "GPT_5.4_pro", "Gemini_3.1_Flash", "Gemini_3.1_Pro")
STRATEGIES = ("sc", "ib", "ng")
PER_MODEL = 500
_COLUMNS = ["human_rid", "ai_article", "model", "strategy", "language"]

SPEC = SourceSpec(
    name="lede",
    licence="CC-BY-NC-4.0",
    licence_class=LicenceClass.NON_COMMERCIAL,
    files=tuple((f"{_BASE}data/Eng/{m}_Eng.csv", f"data/Eng/{m}_Eng.csv") for m in _MODELS),
)


def load(raw: Path, cap: int) -> Iterable[Sample]:
    frames = []
    for path in sorted((raw / "data" / "Eng").glob("*_Eng.csv")):
        stem = path.name.removesuffix("_Eng.csv")
        if not stem.startswith(FRONTIER):
            continue
        df = pd.read_csv(path, usecols=_COLUMNS)
        df = df[df["strategy"].isin(STRATEGIES) & (df["language"] == "eng")]
        frames.append(df.assign(generator=stem.replace("_", " "), key=df["human_rid"].astype(str) + ":" + stem))
    if not frames:
        return
    df = take_per_stratum(pd.concat(frames, ignore_index=True), ["generator"], min(cap, PER_MODEL), "key")
    yield from compact(
        make_sample(SPEC, text=r.ai_article, label=Label.AI, role=Role.CORE, record_id=f"{r.key}:{r.strategy}",
                    domain="news", group_key=str(r.human_rid), generator=r.generator,
                    verification="dataset label (generated by the named model)")
        for r in df.itertuples()
    )
